const src = fs.readFileSync(outFile, 'utf8');
const match = src.match(
  /export const CHARACTER_LIBRARY: CharacterLibraryItem\[\] = (\[[\s\S]*?\n\]);/,
);
if (!match) {
  console.error('parse fail');
  process.exit(1);
}
const items = JSON.parse(match[1]);
const existingIds = new Set(items.map((i) => i.id));
let added = 0;
for (const row of EXTRA) {
  const [id, label, category, tags, blurb, description] = row;
  if (existingIds.has(id)) continue;
  items.push({
    id,
    label,
    category,
    tags,
    blurb,
    description,
    consistencyPrompt: `同一角色：${description.replace(/^外形：/, '').replace(/。性格气质.*$/, '')}，面部五官、发型、服装标志与气质保持一致，多角度可识别。`,
  });
  added += 1;
}

const header = `import type { CharacterLibraryItem } from './types';\n\nexport const CHARACTER_LIBRARY: CharacterLibraryItem[] = `;
const footer = `
export const CHARACTER_CATEGORIES = Array.from(
  new Set(CHARACTER_LIBRARY.map((i) => i.category)),
);
`;
fs.writeFileSync(outFile, `${header}${JSON.stringify(items, null, 2)};\n${footer}`, 'utf8');
console.log(`characters: ${items.length} total, +${added} new`);
