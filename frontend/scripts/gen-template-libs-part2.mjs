const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '../src/libraries');

function writeLib(file, constName, arr, catsExport) {
  const content = `import type { TemplateLibraryItem } from './types';

export const ${constName}: TemplateLibraryItem[] = ${JSON.stringify(arr, null, 2)};

export const ${catsExport} = Array.from(
  new Set(${constName}.map((i) => i.category)),
);
`;
  fs.writeFileSync(path.join(root, file), content);
}

function build(prefix, cats) {
  const out = [];
  for (const g of cats) {
    g.items.forEach((row, i) => {
      const [label, blurb, content] = row;
      out.push({
        id: `${prefix}-${g.cat}-${String(i + 1).padStart(2, '0')}`,
        label,
        category: g.cat,
        tags: g.tags,
        blurb,
        content,
      });
    });
  }
  return out;
}

