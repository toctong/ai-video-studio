function buildFromCats(cats) {
  const scripts = [];
  for (const g of cats) {
    g.items.forEach((row, i) => {
      const [label, blurb, ideaCore] = row;
      scripts.push({
        id: `script-${g.cat}-${String(i + 1).padStart(2, '0')}`,
        label,
        category: g.cat,
        tags: g.tags,
        blurb,
        idea: `题材：${g.cat}。${ideaCore}默认男主主视角；女主可作情感线或关键配。节奏适合网文连载，章末留钩子。`,
        sampleSkeleton: skeleton(blurb),
      });
    });
  }
  return scripts;
}

