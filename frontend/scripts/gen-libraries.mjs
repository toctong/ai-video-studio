function writeLib(file, constName, typeName, arr, catsExport) {
  const content = `import type { ${typeName} } from './types';

export const ${constName}: ${typeName}[] = ${JSON.stringify(arr, null, 2)};

export const ${catsExport} = Array.from(
  new Set(${constName}.map((i) => i.category)),
);
`;
  fs.writeFileSync(path.join(root, file), content);
}

