import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const libDir = path.join(__dirname, '../src/libraries');

function pad(n) {
  return String(n).padStart(2, '0');
}

function writeLib(file, typeImport, constName, items, typeName) {
  const header = `import type { ${typeImport} } from './types';\n\nexport const ${constName}: ${typeName}[] = `;
  const catConst = constName.replace('_LIBRARY', '_CATEGORIES');
  const footer = `\nexport const ${catConst} = Array.from(\n  new Set(${constName}.map((i) => i.category)),\n);\n`;
  fs.writeFileSync(path.join(libDir, file), `${header}${JSON.stringify(items, null, 2)};\n${footer}`, 'utf8');
  const cats = [...new Set(items.map((i) => i.category))];
  console.log(`${file}: ${items.length} items, ${cats.length} cats`);
}

function readArray(file, constName) {
  const src = fs.readFileSync(path.join(libDir, file), 'utf8');
  const re = new RegExp(`export const ${constName}[^=]*= (\\[[\\s\\S]*?\\n\\]);`);
  const m = src.match(re);
  if (!m) throw new Error(`parse fail ${file} ${constName}`);
  return JSON.parse(m[1]);
}

function mergeById(existing, extras) {
  const map = new Map(existing.map((i) => [i.id, i]));
  for (const e of extras) map.set(e.id, e);
  return Array.from(map.values());
}

function templateItem(prefix, cat, n, label, tags, blurb, content) {
  return {
    id: `${prefix}-${cat}-${pad(n)}`,
    label,
    category: cat,
    tags,
    blurb,
    content,
  };
}

