function item(p) {
  return { durationSec: 10, ...p };
}

function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function dumpShot(s) {
  const roles = (s.castRoles || []).map((r) => `      '${esc(r)}',`).join('\n');
  const tags = (s.tags || []).map((t) => `'${esc(t)}'`).join(', ');
  const castRolesBlock =
    (s.castRoles || []).length === 0
      ? '    castRoles: [],'
      : `    castRoles: [
${roles}
    ],`;
  return `  {
    id: '${esc(s.id)}',
    label: '${esc(s.label)}',
    category: '${esc(s.category)}',
    tags: [${tags}],
    blurb: '${esc(s.blurb)}',
    castCount: ${s.castCount},
${castRolesBlock}
    cameraFocus: '${esc(s.cameraFocus)}',
    moveFocus: '${esc(s.moveFocus)}',
    vfxFocus: '${esc(s.vfxFocus)}',
    sceneHint: '${esc(s.sceneHint)}',
    seed: '${esc(s.seed)}',
    durationSec: ${s.durationSec || 10},
  }`;
}

function dumpFile(exportName, comment, arr) {
  const body = arr.map(dumpShot).join(',\n');
  return `import type { ShotLibraryItem } from '../types';

/** ${comment} */
export const ${exportName}: ShotLibraryItem[] = [
${body},
];
`;
}

