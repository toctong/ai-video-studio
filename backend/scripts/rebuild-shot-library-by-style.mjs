function isFightRow(row) {
  const extraTags = Array.isArray(row[10]) ? row[10] : [];
  const text = `${row[1] || ''}${row[3] || ''}${row[5] || ''}${row[6] || ''}${row[9] || ''}`;
  return (
    extraTags.some((t) => /超燃战斗|战力天花板|大招特写/.test(String(t))) ||
    /对决|对斩|对轰|交锋|对拳|打斗|战斗|拔刀|连斩|互殴|大招|归宗|齐发/.test(
      text,
    )
  );
}

/** 整合旧打斗种子：招式打斗 + 专武/拿手特写 + 命名大招 */
function enrichFightRow(row) {
  if (!isFightRow(row)) return row;
  const copy = [...row];
  let [n, label, style, blurb, roles, cam, mov, vfx, scene, seed, extraTags] =
    copy;
  extraTags = Array.isArray(extraTags) ? [...extraTags] : [];
  if (!extraTags.includes('超燃战斗')) extraTags.push('超燃战斗');
  if (!extraTags.includes('大招特写')) extraTags.push('大招特写');
  if (!extraTags.includes('招式打斗')) extraTags.push('招式打斗');
  if (!extraTags.includes('炫技连招')) extraTags.push('炫技连招');

  if (!/特写|微距|升格|刃|枪|棍|弓|拳|掌|印|尾|锤|弦|炮|瞳|指/.test(String(cam))) {
    cam = `专武或拿手绝技微距特写→${cam}`;
  }
  if (
    !/旋风|拔刀|龙抬头|十字|影杀|虚影|焚天|开天|火龙|归宗|齐发|破界|大招|招式/.test(
      `${mov}${blurb}`,
    )
  ) {
    mov = `${mov}；炫技连招（虚影步/旋风斩/十字斩等）+高潮命名大招打中对手`;
  }
  if (!/招式打斗|命名大招|大招|专武|绝技|炫技|旋风|拔刀/.test(String(seed))) {
    seed = `${seed} 拉风技能硬锁：禁止捅来捅去；用命名技能打（剑：拔刀斩/龙抬头/一剑开天门/十字斩/万剑归宗；刀：旋风斩/影杀/刀域一闪；枪棍：千枪齐发/棍扫千军；拳掌：焚天决/火龙卷/一拳破界；身法：虚影步/踏云步）——核心招写透+终局大招打中对手；场景裂仅同轴余波。`;
  } else if (!/打中|命中|空地|噶|同轴|余波/.test(String(seed))) {
    seed = `${seed} 终局硬锁：大招必须打中对手；场景形变若有须同轴余波；禁止互捅、禁止人站着背景自炸。`;
  } else if (!/炫技|旋风|拔刀|捅|技能轮换/.test(String(seed))) {
    seed = `${seed} 炫技：核心命名技能写透+身法步法，禁止平刺来回。`;
  }
  if (!/规格|暴雨|半屏|缩水|上百/.test(String(seed))) {
    seed = `${seed} 大招规格：名字含千/万/阵/域/决/开天/破界/灭世者须满屏体量（暴雨成幕/罩敌半屏），禁止缩成几道小特效；本命兵器握柄不断；禁止烧录技能大字。`;
  }
  if (!/招式|大招|特写|炫技|技能/.test(String(blurb))) {
    blurb = `${blurb}（拉风技能连招：专武特写与命名大招高潮）`;
  }
  return [n, label, style, blurb, roles, cam, mov, vfx, scene, seed, extraTags];
}

function build(cat, prefix, rows) {
  return rows.map((raw) => {
    const row = enrichFightRow(raw);
    const [n, label, style, blurb, roles, cam, mov, vfx, scene, seed, extraTags] =
      row;
    const tags = [style, '画风', ...(Array.isArray(extraTags) ? extraTags : [])];
    // 除写实质感外：统一打上动漫风底盘标签（子风格仍是色板/特效味）
    if (cat !== CAT.real && !tags.includes('动漫风')) {
      tags.splice(2, 0, '动漫风');
    }
    return item({
      id: `shot-${prefix}-${n}`,
      label,
      category: cat,
      tags,
      blurb: `${cat}·${style}：${blurb}`,
      castCount: roles.length,
      castRoles: roles,
      cameraFocus: cam,
      moveFocus: mov,
      vfxFocus: vfx,
      sceneHint: scene,
      seed,
    });
  });
}

